export function getNextEvent(): Event {
  const now = new Date();
  const upcoming = EVENTS.filter((e) => new Date(e.date) > now).sort(
    (a, b) => new Date(a.date).getTime() - new Date(b.date).getTime()
  );
  return upcoming[0] ?? EVENTS[0];
}
